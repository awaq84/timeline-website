// Markers are drawn in viewBox units and scaled by 1/zoom so they stay a
// constant size on screen as you zoom. That holds on desktop, where the 960-unit
// viewBox renders at roughly 960px. On a 375px phone the same viewBox is scaled
// to 0.39, so the 11-unit halo lands as an 8.6px tap target -- a fifth of the
// ~44px a fingertip needs, on the one control the whole page exists to offer.
//
// Scaling the marker layer back up on phones costs nothing on the map itself:
// dots already overlap at this size and the existing fan-out handles co-located
// ones. Read on each use rather than cached, so rotating the phone or resizing
// picks up the change without a reload.
const markerScale = () => (window.matchMedia("(max-width: 640px)").matches ? 2 : 1);

function initMap() {
  svg = d3
    .select("#map")
    .append("svg")
    .attr("viewBox", `0 0 ${MAP_WIDTH} ${MAP_HEIGHT}`);

  projection = d3.geoNaturalEarth1().scale(160).translate([MAP_WIDTH / 2, MAP_HEIGHT / 2]);
  path = d3.geoPath(projection);

  // A hatch rather than a flat fill. Thirteen category colours are already in
  // play on this map, and a fourteenth solid colour would read as another
  // category; diagonal stripes read as "provisional" in every atlas ever
  // printed. patternUnits is userSpaceOnUse so the stripes stay put against the
  // map rather than shifting inside each shape.
  const defs = svg.append("defs");
  const hatch = defs
    .append("pattern")
    .attr("id", "disputedHatch")
    .attr("patternUnits", "userSpaceOnUse")
    .attr("width", 9)
    .attr("height", 9)
    .attr("patternTransform", "rotate(45)");
  // Deliberately faint. This is a footnote on the map, not a category: it should
  // be findable when you look for it and invisible when you are not. Wider
  // spacing and a thinner, dimmer line read as texture rather than as a fill.
  hatch.append("rect").attr("width", 9).attr("height", 9).attr("fill", "none");
  hatch.append("line").attr("x1", 0).attr("y1", 0).attr("x2", 0).attr("y2", 9).attr("stroke", "rgba(255, 255, 255, 0.16)").attr("stroke-width", 0.8);

  zoomLayer = svg.append("g").attr("class", "zoom-layer");
  const landLayer = zoomLayer.append("g").attr("class", "land-layer");
  // Between the land and the markers: over the country fills so the hatch is
  // visible, under the markers so it never sits on top of a dot.
  disputedLayer = zoomLayer.append("g").attr("class", "disputed-layer");
  markerLayer = zoomLayer.append("g").attr("class", "marker-layer");

  zoomBehavior = d3
    .zoom()
    .scaleExtent([1, 14])
    .translateExtent([
      [0, 0],
      [MAP_WIDTH, MAP_HEIGHT],
    ])
    .extent([
      [0, 0],
      [MAP_WIDTH, MAP_HEIGHT],
    ])
    .on("start", () => {
      svg.classed("zooming", true);
      dismissZoomHint();
    })
    .on("zoom", (event) => {
      currentZoomK = event.transform.k;
      zoomLayer.attr("transform", event.transform);
      markerLayer.selectAll(".marker-visual").attr("transform", `scale(${markerScale() / currentZoomK})`);
      // Fan offsets are screen-space, so they are divided by the zoom factor and
      // have to be recomputed here or co-located markers drift apart as you zoom.
      if (markerFanOffsets.size) markerLayer.selectAll("g.event-marker").attr("transform", markerTransform);
      scheduleLabelReflow();
    })
    .on("end", () => {
      svg.classed("zooming", false);
    });

  svg.call(zoomBehavior);

  zoomInBtn?.addEventListener("click", () => {
    dismissZoomHint();
    svg.transition().duration(220).call(zoomBehavior.scaleBy, 1.6);
  });
  zoomOutBtn?.addEventListener("click", () => {
    dismissZoomHint();
    svg.transition().duration(220).call(zoomBehavior.scaleBy, 1 / 1.6);
  });
  zoomResetBtn?.addEventListener("click", () => {
    dismissZoomHint();
    svg.transition().duration(300).call(zoomBehavior.transform, d3.zoomIdentity);
  });

  d3.json("https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json").then((world) => {
    const countries = topojson.feature(world, world.objects.countries);
    landLayer
      .selectAll("path")
      .data(countries.features)
      .join("path")
      .attr("class", "land")
      .attr("d", path);
    drawDisputedAreas();
    renderAll();
  });
}

// Territories whose sovereignty is contested, drawn over the country shapes in a
// hatch so they read as "this is not settled" rather than as another country.
//
// The base atlas draws one set of present-day borders and says nothing about
// which of them anyone disagrees with. It happens to carry Taiwan, Palestine,
// Kosovo, W. Sahara, N. Cyprus and Somaliland as separate shapes, but not
// Kashmir, Crimea, the Golan Heights or Nagorno-Karabakh -- those are folded
// into a neighbour. Marking only the ones the atlas happened to split out would
// have looked like an editorial line rather than an omission, which is worse
// than marking none, so this layer comes from Natural Earth's dedicated
// disputed-areas dataset instead, which carries all 79.
//
// Carries, not shows. About half render to under a pixel at world scale --
// Gibraltar, the Spratlys, Scarborough Reef, Hans Island, Rockall, Mount Scopus
// and 30-odd others are territories whose whole point is that they are tiny.
// Zoom is an SVG transform over already-projected paths, so those stay invisible
