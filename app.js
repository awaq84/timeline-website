// "BC" rather than "BCE" to match the static year pages, which use it because
// it is what people actually search for -- "44 BC" outweighs "44 BCE" by a wide
// margin, and the app links straight through to those pages.
function formatYear(y) {
  return y < 0 ? `${Math.abs(y)} BC` : `${y}`;
}

// ---- Timeline scale ----
//
// The slider used to map position to year linearly, which spent 82.6% of the
// track on 0.58% of the events: 919 events lie before 500 BC, spread over
// 11,980 years, while the other 158,174 were crushed into the remaining 17.4%.
// A pixel near the right-hand end was worth sixteen years, so the entire
// twentieth century sat inside about seven pixels.
//
// So the track is now piecewise. Everything from 500 BC onward gets exactly one
// slider position per year -- arrow keys step a single year, and the dense part
// of history is where nearly all the track goes. The thin pre-500 BC stretch is
// compressed into a tenth of the width, which is still far more room than its
// share of the events would justify, because a timeline that visibly reaches
// back to 12480 BC is worth more than the pixels it costs.
//
// Positions are integers because that is what <input type="range"> steps in.
// state.year stays the source of truth; the slider is only a view of it, so a
// rounded position never feeds back into the year.
const SCALE = { min: -500, max: 2026, split: -500, sparsePositions: 0, positions: 1 };

// Below this year the data is too thin to deserve linear space. 500 BC is where
// the dataset stops being sparse: 919 events before it, 158,174 after.
const SCALE_SPLIT_YEAR = -500;
// Share of the track given to everything before the split.
const SPARSE_TRACK_SHARE = 0.1;

function buildTimelineScale(minYear, maxYear) {
  SCALE.min = minYear;
  SCALE.max = maxYear;
  SCALE.split = Math.max(minYear, Math.min(SCALE_SPLIT_YEAR, maxYear));
  const densePositions = Math.max(1, SCALE.max - SCALE.split);
  // No sparse region at all when the dataset starts after the split, which keeps
  // this correct if the earliest event ever moves forward.
  SCALE.sparsePositions =
    SCALE.split > minYear ? Math.max(1, Math.round((densePositions * SPARSE_TRACK_SHARE) / (1 - SPARSE_TRACK_SHARE))) : 0;
  SCALE.positions = SCALE.sparsePositions + densePositions;
}

function posToYear(pos) {
  const p = Math.min(Math.max(Math.round(pos), 0), SCALE.positions);
  if (p >= SCALE.sparsePositions) return SCALE.split + (p - SCALE.sparsePositions);
  return Math.round(SCALE.min + ((SCALE.split - SCALE.min) * p) / SCALE.sparsePositions);
}

function yearToPos(year) {
  const y = Math.min(Math.max(year, SCALE.min), SCALE.max);
  if (y >= SCALE.split) return SCALE.sparsePositions + (y - SCALE.split);
  return Math.round(((y - SCALE.min) / (SCALE.split - SCALE.min)) * SCALE.sparsePositions);
}

// An event carries `prec` only when Wikidata's own date is vaguer than a year:
// 6 millennium, 7 century, 8 decade. Wikidata renders such a date as a concrete
// January 1st, so "12th century" reaches us as 1101 or 1150 depending on the
// item, and thousands of events piled onto those anchor years looking exact.
//
// They still sit at the anchor year on the timeline -- it's the only position we
// have, and it's right to within a century -- but the event list says what the
// source actually claims rather than parroting the anchor. Kept in step with
// precisionLabel() in scripts/build-year-pages.mjs.
const ordinalSuffix = (n) => {
  const r = n % 100;
  if (r >= 11 && r <= 13) return `${n}th`;
  return `${n}${{ 1: "st", 2: "nd", 3: "rd" }[n % 10] || "th"}`;
};

// Wikibase derives the ordinal from the astronomical year (the one where 0 exists
// and means 1 BC), so -0400 at century precision is "4th century BC" in Wikidata's
// own renderer. We store display years, so convert back before the arithmetic or
// every BC label lands one century out. Kept in step with precisionLabel() in
// scripts/build-year-pages.mjs.
function precisionLabel(e) {
  if (!e.prec) return null;
  const a = e.year < 0 ? e.year + 1 : e.year;
  const bc = a <= 0;
  const mag = Math.abs(a);
  if (e.prec === 8) return `${Math.floor(mag / 10) * 10}s${bc ? " BC" : ""}`;
  const size = e.prec === 7 ? 100 : 1000;
  const word = e.prec === 7 ? "century" : "millennium";
  return `${ordinalSuffix(Math.max(1, Math.ceil(mag / size)))} ${word}${bc ? " BC" : ""}`;
}

// ---- Data access ----
//
// The dataset is 111,389 events / 28MB. Shipping all of it before the first
// paint cost about six seconds on a good connection and far worse on a phone,
// so scripts/build-chunks.mjs splits it into a 27KB index plus 69 era chunks
// fetched on demand. The map only ever displays one year, and a year is never
// split across chunks, so a render touches exactly one of them.
//
// INDEX holds every year that has events together with a bitmask of which
// categories appear in it. That is deliberately enough to drive the slider, the
// step/play buttons and the nearest-year hint *synchronously* -- those have to
// answer "which years have anything" across the whole timeline, and making them
// wait on the network would feel broken.

let INDEX = null;
let catBit = new Map(); // category name -> its bit position in the year mask

// Resolved chunks and in-flight requests are tracked separately so callers can
// ask "is this already here?" without going through a promise. Awaiting even an
// already-resolved promise costs a microtask, and that is enough to make the
// slider visibly trail the handle while dragging.
const chunkData = new Map();
const chunkPending = new Map();

// Roughly 18,000 events held at once. Scrubbing the full timeline would
// otherwise accumulate all 69 chunks, and 28MB of JSON inflates to well over
// 100MB once parsed into objects -- enough to get the tab killed on a phone.
const MAX_CACHED_CHUNKS = 12;

const chunkUrl = (n) => `data/events/${String(n).padStart(3, "0")}.json`;

async function loadIndex() {
  const res = await fetch("data/index.json");
  if (!res.ok) throw new Error(`data/index.json: HTTP ${res.status}`);
  INDEX = await res.json();
  catBit = new Map(INDEX.categories.map((c, i) => [c, i]));
}

// chunkStarts ascends and the ranges tile the timeline with no gaps, so the
// chunk holding a year is the last one starting at or before it. Binary search
// because this runs on every slider tick.
function chunkForYear(year) {
  const starts = INDEX.chunkStarts;
  if (year <= starts[0]) return 0;
  let lo = 0;
  let hi = starts.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (starts[mid] <= year) lo = mid;
    else hi = mid - 1;
  }
  return lo;
}

function loadChunk(n) {
  const have = chunkData.get(n);
  if (have) return Promise.resolve(have);
  const inFlight = chunkPending.get(n);
  if (inFlight) return inFlight;

  const p = fetch(chunkUrl(n))
    .then((res) => {
      if (!res.ok) throw new Error(`${chunkUrl(n)}: HTTP ${res.status}`);
      return res.json();
    })
    .then((rows) => {
      chunkPending.delete(n);
      chunkData.set(n, rows);
      // Map iterates in insertion order, so the first key is the oldest.
      while (chunkData.size > MAX_CACHED_CHUNKS) {
        chunkData.delete(chunkData.keys().next().value);
      }
      return rows;
    })
    .catch((err) => {
      // Forget the failure rather than caching it, so scrubbing back to this
      // era retries instead of showing the same error forever.
      chunkPending.delete(n);
      throw err;
    });

  chunkPending.set(n, p);
  return p;
}

// Warm the neighbours so stepping or playing across a chunk boundary doesn't
// stall. Failures here are irrelevant -- the real render will retry and report.
function prefetchNeighbours(n) {
  for (const m of [n + 1, n - 1]) {
    if (m >= 0 && m < INDEX.chunkStarts.length && !chunkData.has(m) && !chunkPending.has(m)) {
      loadChunk(m).catch(() => {});
    }
  }
}

function activeMask() {
  let mask = 0;
  for (const c of state.activeCategories) {
    const bit = catBit.get(c);
    if (bit !== undefined) mask |= 1 << bit;
  }
  return mask;
}

// Years carrying at least one event in an active category. Already ascending in
// the index, so no sort is needed.
function getEventYears() {
  if (!INDEX) return [];
  const mask = activeMask();
  if (!mask) return [];
  const out = [];
  for (const [y, m] of INDEX.years) if (m & mask) out.push(y);
  return out;
}

// Builds a marker-lookalike swatch (coloured disc + category glyph) for use in
// the filter list and the pinned event card.
function categorySwatch(cat, size = 18) {
  const svgNS = "http://www.w3.org/2000/svg";
  const iconSize = size * 0.6875; // matches the map's 8:11 dot-to-glyph ratio
  const svg = document.createElementNS(svgNS, "svg");
  svg.setAttribute("class", "chip-dot");
  svg.setAttribute("width", size);
  svg.setAttribute("height", size);
  svg.setAttribute("viewBox", `${-size / 2} ${-size / 2} ${size} ${size}`);
  svg.setAttribute("aria-hidden", "true");

  const circle = document.createElementNS(svgNS, "circle");
  circle.setAttribute("r", size / 2 - 0.75);
  circle.setAttribute("fill", CATEGORY_COLORS[cat] || "#888");
  svg.appendChild(circle);

  if (CATEGORY_ICONS[cat]) {
    const g = document.createElementNS(svgNS, "g");
    g.setAttribute("transform", `translate(${-iconSize / 2},${-iconSize / 2}) scale(${iconSize / 24})`);
    const p = document.createElementNS(svgNS, "path");
    p.setAttribute("d", CATEGORY_ICONS[cat]);
    g.appendChild(p);
    svg.appendChild(g);
  }
  return svg;
}

function buildCategoryFilters() {
  categoryFiltersEl.innerHTML = "";
  CATEGORY_ORDER.forEach((cat) => {
    const id = `cat-${cat.replace(/[^a-z0-9]/gi, "")}`;
    const wrapper = document.createElement("label");
    wrapper.className = "chip";
    wrapper.setAttribute("for", id);

    const checkbox = document.createElement("input");
    checkbox.type = "checkbox";
    checkbox.className = "chip-input";
    checkbox.id = id;
    checkbox.checked = state.activeCategories.has(cat);
    checkbox.addEventListener("change", () => {
      if (checkbox.checked) state.activeCategories.add(cat);
      else state.activeCategories.delete(cat);
      renderAll();
    });

    // The swatch shows the same colour *and* glyph as the map marker, so the
    // filter list doubles as the map legend -- 13 glyphs is more than anyone
    // will memorise from the map alone.
    const swatch = categorySwatch(cat);

    wrapper.appendChild(checkbox);
    wrapper.appendChild(swatch);
    wrapper.appendChild(document.createTextNode(cat));
    categoryFiltersEl.appendChild(wrapper);
  });
}

