// The static year pages under /year/ link back here as /?year=1969, and BC years
// arrive negative (/?year=-44). Parsed before the range is applied so an
// out-of-dataset year is clamped by the same code that clamps the default.
function yearFromUrl() {
  const raw = new URLSearchParams(location.search).get("year");
  if (raw === null) return null;
  const y = Number(raw);
  return Number.isInteger(y) ? y : null;
}

// Keep the address bar in step with the slider so a view can be linked or
// bookmarked. replaceState, not pushState: scrubbing fires this constantly and
// pushing would bury the back button under hundreds of entries.
let urlSyncTimer = null;
function syncUrlToYear() {
  clearTimeout(urlSyncTimer);
  urlSyncTimer = setTimeout(() => {
    const url = new URL(location.href);
    url.searchParams.set("year", state.year);
    history.replaceState(null, "", url);
  }, 400);
}

function initTimelineRange() {
  const { minYear, maxYear } = INDEX;

  const urlYear = yearFromUrl();
  if (urlYear !== null) state.year = urlYear;

  buildTimelineScale(minYear, maxYear);
  yearSlider.min = 0;
  yearSlider.max = SCALE.positions;
  if (state.year < minYear || state.year > maxYear) {
    state.year = Math.min(Math.max(state.year, minYear), maxYear);
  }
  yearSlider.value = yearToPos(state.year);

  // The compressed stretch is shaded differently so the change of scale is
  // visible rather than something you have to infer from the labels.
  yearSlider.style.setProperty("--split", `${(SCALE.sparsePositions / SCALE.positions) * 100}%`);

  const timelineLabelsEl = document.querySelector(".timeline-labels");
  if (timelineLabelsEl) {
    const stops = 7;
    timelineLabelsEl.innerHTML = "";
    for (let i = 0; i < stops; i++) {
      // Stops are spaced evenly along the TRACK and then converted to years, so
      // they report where the scale actually puts things. Spacing them evenly in
      // years would print a ruler that disagrees with the thumb underneath it.
      const y = posToYear(Math.round((SCALE.positions * i) / (stops - 1)));
      const span = document.createElement("span");
      span.textContent = formatYear(y);
      timelineLabelsEl.appendChild(span);
    }
  }

  if (datasetStatEl) {
    const byCategory = new Map(INDEX.categories.map((c, i) => [c, INDEX.categoryCounts[i]]));
    const breakdown = CATEGORY_ORDER.filter((c) => byCategory.has(c))
      .map((c) => `${c} (${byCategory.get(c)})`)
      .join(", ");
    datasetStatEl.innerHTML = `<strong>${INDEX.total.toLocaleString()} events</strong> spanning ${formatYear(minYear)} &ndash; ${formatYear(maxYear)}.`;
    datasetStatEl.title = breakdown;
  }
}

